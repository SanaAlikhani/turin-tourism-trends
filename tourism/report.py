"""Charts and a plain-language findings file generated from the database."""
from __future__ import annotations

import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no display needed
import matplotlib.pyplot as plt
import pandas as pd

from .analysis import cagr, run_query

TEAL, AMBER, RED, GREY = "#0f6b5c", "#b87800", "#b0372c", "#6b7770"
SOURCE = "Source: Comune di Torino / ARPA Piemonte, CC BY 4.0"


def _style(ax) -> None:
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(axis="y", alpha=0.25)


def _footer(fig) -> None:
    fig.text(0.01, 0.01, SOURCE, fontsize=8, color=GREY)


def chart_trends(yearly: pd.DataFrame, path: Path) -> None:
    fig, (top, bottom) = plt.subplots(2, 1, figsize=(9, 6.4), sharex=True)
    top.plot(yearly["year"], yearly["tourists"] / 1e6, color=TEAL, marker="o", ms=3.5, lw=2)
    top.set_ylabel("Tourist arrivals (millions)")
    bottom.plot(yearly["year"], yearly["businesses"], color=AMBER, marker="o", ms=3.5, lw=2)
    bottom.set_ylabel("Accommodation businesses")
    for ax in (top, bottom):
        _style(ax)
        ax.axvline(2006, color=GREY, ls="--", lw=1)
    low, high = top.get_ylim()
    top.text(2006.2, low + 0.04 * (high - low), "Winter Olympics 2006", fontsize=9, color=GREY)
    bottom.set_xticks(range(int(yearly["year"].min()), int(yearly["year"].max()) + 1, 4))
    fig.suptitle("Tourism in the Turin area, 1994-2018", fontsize=13, fontweight="bold")
    fig.tight_layout(rect=(0, 0.03, 1, 0.97))
    _footer(fig)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def chart_per_business(yearly: pd.DataFrame, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(9, 4.2))
    ax.plot(yearly["year"], yearly["tourists_per_business"], color=TEAL, marker="o", ms=3.5, lw=2)
    ax.set_ylabel("Tourist arrivals per accommodation business")
    ax.set_xticks(range(int(yearly["year"].min()), int(yearly["year"].max()) + 1, 4))
    _style(ax)
    ax.set_title("How busy is each business? Arrivals per business", fontsize=13, fontweight="bold")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    _footer(fig)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def chart_yoy(growth: pd.DataFrame, path: Path) -> None:
    data = growth.dropna(subset=["tourists_yoy_pct"])
    colors = [RED if v < 0 else TEAL for v in data["tourists_yoy_pct"]]
    fig, ax = plt.subplots(figsize=(9, 4.2))
    ax.bar(data["year"], data["tourists_yoy_pct"], color=colors)
    ax.axhline(0, color=GREY, lw=1)
    ax.set_ylabel("Change vs previous year (%)")
    ax.set_xticks(range(int(data["year"].min()), int(data["year"].max()) + 1, 2))
    _style(ax)
    ax.set_title("Year-on-year change in tourist arrivals", fontsize=13, fontweight="bold")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    _footer(fig)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def build_findings(con: sqlite3.Connection) -> str:
    growth = run_query(con, "yearly_growth")
    first, last = growth.iloc[0], growth.iloc[-1]
    span = int(last["year"] - first["year"])
    y0, y1 = int(first["year"]), int(last["year"])

    def change(a: float, b: float) -> str:
        return f"{(b / a - 1) * 100:+.0f}%"

    peak = run_query(con, "peak_tourists_per_business").iloc[0]
    biggest = run_query(con, "biggest_arrival_changes")
    declines = run_query(con, "years_with_declines")
    periods = run_query(con, "five_year_periods")

    fell_tourists = [str(int(y)) for y in declines.loc[declines["tourists_fell"] == 1, "year"]]
    fell_businesses = [str(int(y)) for y in declines.loc[declines["businesses_fell"] == 1, "year"]]

    out = [
        f"# Findings: tourism in the Turin area, {y0}-{y1}",
        "",
        "Generated by `python -m tourism` from the SQLite database. Do not edit by hand.",
        "",
        "## Headline numbers",
        "",
        f"- **Tourist arrivals** went from {int(first['tourists']):,} in {y0} to {int(last['tourists']):,} in {y1} "
        f"({change(first['tourists'], last['tourists'])}), a compound growth of "
        f"{cagr(first['tourists'], last['tourists'], span) * 100:.1f}% a year.",
        f"- **Accommodation businesses** went from {int(first['businesses']):,} to {int(last['businesses']):,} "
        f"({change(first['businesses'], last['businesses'])}), or "
        f"{cagr(first['businesses'], last['businesses'], span) * 100:.1f}% a year.",
        f"- **Arrivals per business** went from {first['tourists_per_business']:,.0f} to "
        f"{last['tourists_per_business']:,.0f}; the highest value was {peak['tourists_per_business']:,.0f} in {int(peak['year'])}.",
        f"- Arrivals fell compared with the previous year in: {', '.join(fell_tourists) or 'no year'}.",
        f"- The number of businesses fell in: {', '.join(fell_businesses) or 'no year'}.",
        "",
        "## Biggest year-on-year changes in arrivals",
        "",
        _table(
            ["Year", "Previous year", "This year", "Change"],
            [
                [str(int(r.year)), f"{int(r.previous_year_tourists):,}", f"{int(r.tourists):,}", f"{r.change_pct:+.1f}%"]
                for r in biggest.itertuples()
            ],
        ),
        "",
        "## Five-year averages",
        "",
        _table(
            ["Period", "Avg arrivals", "Avg businesses", "Avg arrivals per business"],
            [
                [r.period, f"{int(r.avg_tourists):,}", f"{int(r.avg_businesses):,}", f"{r.avg_tourists_per_business:,.1f}"]
                for r in periods.itertuples()
            ],
        ),
        "",
        "## Read with care",
        "",
        "- The data are provincial totals (Province of Turin), not figures for the city alone.",
        "- The dataset gives totals only. It does not explain the large jumps (for example the rise between 2004 and 2005, "
        "or between 2008 and 2009), so this analysis does not attribute causes. Check the methodology of the original "
        "ARPA Piemonte indicator before drawing conclusions about events such as the 2006 Winter Olympics.",
        "- A reported rise in arrivals per business means busier businesses on average, not necessarily higher profit or occupancy.",
        "",
    ]
    return "\n".join(out)


def write_report(db_path: str | Path, out_dir: str | Path) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(db_path)
    try:
        yearly = pd.read_sql_query("SELECT * FROM tourism_yearly ORDER BY year", con)
        growth = run_query(con, "yearly_growth")
        findings = build_findings(con)
    finally:
        con.close()

    paths = [out_dir / "trends.png", out_dir / "arrivals_per_business.png", out_dir / "yoy_arrivals.png", out_dir / "findings.md"]
    chart_trends(yearly, paths[0])
    chart_per_business(yearly, paths[1])
    chart_yoy(growth, paths[2])
    paths[3].write_text(findings, encoding="utf-8")
    return paths
